"""PostgreSQL (Neon) storage shared by the app's features, using psycopg.

The connection string comes from DATABASE_URL. Tables are created at startup
if they are missing. Rows come back as dicts, so code reads them as row["name"].

Timestamps are stored as UTC text like "2026-11-12 03:00:00" (the format the
app has always used), and dates as "YYYY-MM-DD" text.
"""
from datetime import date

import psycopg
from flask import current_app, g
from psycopg.rows import dict_row

# Raised when a UNIQUE (or other) constraint is broken. Other modules catch this
# instead of importing psycopg. After catching it, call get_db().rollback().
IntegrityError = psycopg.IntegrityError

# SQL for "now" and "today" in UTC, in the same text format as the stored values.
NOW_TEXT = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')"
TODAY_TEXT = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD')"

SCHEMA = [
    # Accounts. Only Werkzeug password hashes are stored, never plain text.
    f"""CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT {NOW_TEXT}
    )""",
    # One row per compost route day; UNIQUE route_date means one volunteer per day.
    f"""CREATE TABLE IF NOT EXISTS compost_signups (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        route_date TEXT NOT NULL UNIQUE,
        username TEXT NOT NULL,
        training_date TEXT,
        created_at TEXT NOT NULL DEFAULT {NOW_TEXT}
    )""",
    # Plant Help board.
    f"""CREATE TABLE IF NOT EXISTS questions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL,
        topic TEXT NOT NULL,
        title TEXT NOT NULL,
        body TEXT NOT NULL,
        helpful_answer_id BIGINT,
        photo_key TEXT,
        created_at TEXT NOT NULL DEFAULT {NOW_TEXT}
    )""",
    f"""CREATE TABLE IF NOT EXISTS answers (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
        username TEXT NOT NULL,
        body TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT {NOW_TEXT}
    )""",
    # Garden Journal (posts by the garden manager).
    f"""CREATE TABLE IF NOT EXISTS journal_posts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL,
        kind TEXT NOT NULL,
        title TEXT NOT NULL,
        body TEXT NOT NULL,
        link_url TEXT,
        link_title TEXT,
        photo_key TEXT,
        created_at TEXT NOT NULL DEFAULT {NOW_TEXT},
        updated_at TEXT
    )""",
    # Plant Doctor: the AI's first take on a Plant Help question.
    f"""CREATE TABLE IF NOT EXISTS plant_doctor (
        question_id BIGINT PRIMARY KEY REFERENCES questions(id) ON DELETE CASCADE,
        topic TEXT NOT NULL,
        likely_issues TEXT NOT NULL,  -- JSON list of strings
        organic_treatment TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT {NOW_TEXT}
    )""",
    # Farmstand: what's harvested for a given Friday, and produce box reservations.
    """CREATE TABLE IF NOT EXISTS farmstand_days (
        farmstand_date TEXT PRIMARY KEY,
        boxes INTEGER NOT NULL DEFAULT 0,
        note TEXT
    )""",
    f"""CREATE TABLE IF NOT EXISTS harvest_items (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        farmstand_date TEXT NOT NULL,
        name TEXT NOT NULL,
        note TEXT,
        photo_key TEXT,
        created_at TEXT NOT NULL DEFAULT {NOW_TEXT}
    )""",
    f"""CREATE TABLE IF NOT EXISTS box_reservations (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        farmstand_date TEXT NOT NULL,
        username TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT {NOW_TEXT},
        UNIQUE (farmstand_date, username)
    )""",
    # Garden Helper chatbot conversations.
    f"""CREATE TABLE IF NOT EXISTS chat_messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        conversation_id TEXT NOT NULL,
        username TEXT NOT NULL,
        role TEXT NOT NULL,  -- 'user' or 'assistant'
        content TEXT NOT NULL,
        created_at TEXT NOT NULL DEFAULT {NOW_TEXT}
    )""",
    "CREATE INDEX IF NOT EXISTS chat_messages_conversation ON chat_messages (conversation_id)",
    # Columns added after the first release, so older databases get them too.
    "ALTER TABLE questions ADD COLUMN IF NOT EXISTS photo_key TEXT",
    "ALTER TABLE journal_posts ADD COLUMN IF NOT EXISTS photo_key TEXT",
]

# Every table, children first (used to empty the test database).
TABLES = [
    "plant_doctor", "answers", "questions", "users", "compost_signups", "journal_posts",
    "harvest_items", "box_reservations", "farmstand_days", "chat_messages",
]

# Any fixed number works; it just keeps two app instances from creating tables at once.
_SCHEMA_LOCK_ID = 7_404_311
_initialized = set()


def connect(url):
    return psycopg.connect(url, row_factory=dict_row, connect_timeout=10)


def init_db(url):
    """Create any missing tables (once per process for each database)."""
    if url in _initialized:
        return
    with connect(url) as conn:  # commits on success, then closes
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (_SCHEMA_LOCK_ID,))
        for statement in SCHEMA:
            conn.execute(statement)
    _initialized.add(url)


def empty_tables(url):
    """Delete every row and restart ids at 1. Only the tests call this."""
    init_db(url)
    with connect(url) as conn:
        conn.execute(f"TRUNCATE {', '.join(TABLES)} RESTART IDENTITY CASCADE")


def get_db():
    """The PostgreSQL connection for this request (opened on first use)."""
    if "db" not in g:
        g.db = connect(current_app.config["DATABASE_URL"])
    return g.db


def close_db(_exc=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()  # anything not committed is rolled back


def current_date():
    """Today's date; tests can pin it with the TODAY config value."""
    return current_app.config.get("TODAY") or date.today()
